/**
 * Advanced Auto-Detection Technique:
 * 1. Checks navigator.userAgentData (Client Hints API) for high-entropy hardware model (e.g., "2201116PG" for POCO X4 Pro 5G or "SM-A556B")
 * 2. Fallbacks to Screen DPR, Resolution, and User-Agent Regex scoring.
 */
export async function detectDeviceAdvanced() {
  let detectedModelName = '';

  if (navigator.userAgentData && typeof navigator.userAgentData.getHighEntropyValues === 'function') {
    try {
      const hints = await navigator.userAgentData.getHighEntropyValues(['model']);
      if (hints && hints.model) {
        detectedModelName = hints.model;
      }
    } catch (e) {}
  }

  const dpr = window.devicePixelRatio || 1;
  const screenWidth = Math.min(window.screen.width, window.screen.height);
  const screenHeight = Math.max(window.screen.width, window.screen.height);
  const platform = navigator.platform || '';
  const userAgent = (navigator.userAgent || '') + ' ' + detectedModelName;

  let bestMatch = null;
  let bestScore = 0;

  for (const device of deviceDB) {
    const c = device.criteria;
    let score = 0;
    let maxScore = 0;

    if (c.userAgent) {
      maxScore += 50;
      if (c.userAgent.test(userAgent) || (detectedModelName && c.userAgent.test(detectedModelName))) {
        score += 50;
      } else {
        continue; // Skip phone rules if userAgent doesn't match
      }
    }

    if (c.dpr) {
      maxScore += 30;
      if (Math.abs(c.dpr - dpr) < 0.1) score += 30;
      else if (Math.abs(c.dpr - dpr) < 0.3) score += 15;
    }

    if (c.width) {
      maxScore += 20;
      if (Math.abs(c.width - screenWidth) <= 20) score += 20;
      else if (Math.abs(c.width - screenWidth) <= 50) score += 10;
    }

    const matchPercentage = maxScore > 0 ? (score / maxScore) : 0;
    if (matchPercentage > bestScore) {
      bestScore = matchPercentage;
      bestMatch = device;
    }
  }

  return bestMatch;
}

